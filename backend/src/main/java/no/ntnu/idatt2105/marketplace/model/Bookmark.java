package no.ntnu.idatt2105.marketplace.model;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.LocalDateTime;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Entity class representing a bookmark made by a user for a specific item.
 * This class is mapped to the "bookmarks" table in the database.
 */
@Schema(description = "Represents a bookmark where a user saves a listing for later.")
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "bookmarks")
public class Bookmark {

  /**
   * Unique identifier for the bookmark.
   * This field is automatically generated by the database.
   */
  @Schema(description = "Unique identifier for the bookmark.", example = "1")
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  /**
   * The user who bookmarked the item.
   * This field is a foreign key reference to the {@link User} entity.
   */
  @Schema(description = "User who bookmarked the item.", example = "1")
  @ManyToOne(fetch = FetchType.LAZY)
  @JoinColumn(name = "user_id", nullable = false)
  private User user;

  /**
   * The item that was bookmarked.
   * This field is a foreign key reference to the {@link Item} entity.
   */
  @Schema(description = "Item that was bookmarked.", example = "1")
  @ManyToOne(fetch = FetchType.LAZY)
  @JoinColumn(name = "item_id", nullable = false)
  private Item item;

  /**
   * The timestamp when the bookmark was created.
   * This field is automatically set to the current date and time when the bookmark is created.
   */
  @Schema(description = "Timestamp when the bookmark was created.", example = "2023-10-01T12:00:00")
  @Column(nullable = false, updatable = false)
  private LocalDateTime bookmarkedAt = LocalDateTime.now();

  /**
   * Constructor to create a new bookmark with the specified user and item.
   *
   * @param user the user who bookmarked the item
   * @param item the item that was bookmarked
   */
  public Bookmark(User user, Item item) {
    this.user = user;
    this.item = item;
  }
}
